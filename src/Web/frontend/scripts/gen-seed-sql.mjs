// Generates src/Web/supabase/seed/uats_surveys.sql from the committed fixtures:
// real OSM municipality boundaries (data/osm/*) and the survey footprint (organizer study_area, reprojected).
// Run after `pnpm data` (needs public/data/ref/study_area.geojson). Idempotent SQL.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const FRONTEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.resolve(FRONTEND, "../supabase/seed/uats_surveys.sql");
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const geom = (g) => `extensions.st_multi(extensions.st_setsrid(extensions.st_geomfromgeojson(${q(JSON.stringify(g))}), 4326))`;

const UATS = [
  { key: "sireti", file: "sireti_19100171.geojson", name: "Sireți", district: "raionul Strășeni", country: "MD" },
  { key: "cojusna", file: "cojusna_19100156.geojson", name: "Cojușna", district: "raionul Strășeni", country: "MD" },
];
const lines = ["-- generated by src/Web/frontend/scripts/gen-seed-sql.mjs — do not edit by hand", ""];
for (const u of UATS) {
  const f = JSON.parse(fs.readFileSync(path.join(FRONTEND, "data", "osm", u.file), "utf8")).features[0];
  lines.push(
    `insert into public.uat (key, name, district, country, osm_relation_id, geofence) values (${q(u.key)}, ${q(u.name)}, ${q(u.district)}, ${q(u.country)}, ${f.properties.osm_relation_id}, ${geom(f.geometry)})`,
    `  on conflict (key) do update set name = excluded.name, district = excluded.district, country = excluded.country, osm_relation_id = excluded.osm_relation_id, geofence = excluded.geofence;`,
  );
}
const study = JSON.parse(fs.readFileSync(path.join(FRONTEND, "public", "data", "ref", "study_area.geojson"), "utf8")).features[0];
lines.push(
  "",
  `insert into public.survey (id, name, captured_at, source, license, data_path, footprint) values ('siret3-mock', 'Sireț3 — date de test (2 tile-uri exemplu)', '2025-05-20', '3DATA COLLECT / OpenAerialMap', 'CC BY 4.0', '/data/siret3-mock', ${geom(study.geometry)})`,
  `  on conflict (id) do update set name = excluded.name, captured_at = excluded.captured_at, source = excluded.source, license = excluded.license, data_path = excluded.data_path, footprint = excluded.footprint;`,
  "",
);
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${fs.statSync(OUT).size} bytes)`);
